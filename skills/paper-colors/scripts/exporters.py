"""Render a Theme into files a paper project consumes.

Every exported file is self-contained (no import of this skill at build time),
so the paper repo / Overleaf project compiles on any machine.
"""

from __future__ import annotations

import json
from html import escape

import colorlib as cl
from themes import TEXT_ROLES, Theme

REGEN = "python3 ~/.claude/skills/paper-colors/scripts/paper_colors.py export {name} --out <dir>"
MARKERS = ["o", "s", "^", "D", "v", "P", "X"]
LINESTYLES = ["-", "--", "-.", ":", (0, (5, 1)), (0, (3, 1, 1, 1)), (0, (1, 1))]
PGF_MARKS = ["*", "square*", "triangle*", "diamond*", "pentagon*", "o", "square"]
FIXED_TEX = {"highlight": "cHighlight", "gain": "cGain", "drop": "cDrop", "link": "cLink"}


def tex_name(role: str) -> str:
    """Hue role -> LaTeX color name: ours -> cOurs, base1 -> cBase1; text roles fixed."""
    return FIXED_TEX.get(role, "c" + role[:1].upper() + role[1:])


def tex_step_name(role: str, step: int) -> str:
    """cOursS1 (lightest) .. cOursS5 (darkest)."""
    return f"{tex_name(role)}S{step}"


def diagram_tex_name(role: str) -> str:
    return "c" + role.capitalize()


def tex_color_names(theme: Theme) -> set[str]:
    names = {tex_name(r) for r in theme.colors} | {"cArrow"}
    names |= {tex_step_name(r, k) for r, ramp in theme.ramps.items() for k in range(1, len(ramp) + 1)}
    for role in theme.diagram:
        names |= {diagram_tex_name(role), diagram_tex_name(role) + "Fill"}
    return names


# --------------------------------------------------------------------- Python

_PY_TEMPLATE = '''"""Paper colors, theme {name!r}. GENERATED by the paper-colors skill; do not edit.

Regenerate: {regen}

    from paper_colors import C, RAMP, apply, style, ramp
    apply()                                                    # cycle + paper colormaps
    ax.plot(x, y_ours, color=C["ours"], lw=2.2, label="Ours")
    ax.plot(x, y_b1, lw=1.4, label="Baseline A", **style(1))   # role number 1 = base1
    for c, size in zip(ramp("ours", 3, lightest=2), ["S", "M", "L"]):  # ordered, light -> dark
        ax.plot(x, y[size], color=c, label=f"Ours-{{size}}")
"""

THEME = {name!r}

# Hue roles -> anchor (sRGB hex), plus text roles taken from ramp steps.
C = {colors}
CODES = {codes}

# Light -> dark ramps per hue; RAMP[role][ANCHOR_STEP[role] - 1] == C[role].
RAMP = {ramps}
RAMP_CODES = {ramp_codes}   # color book code per step, None = derived step
ANCHOR_STEP = {anchor_step}

CYCLE = {cycle}          # ours, base1.., neutral
SERIES = {series}         # style(i): 0 = ours, i = base<i>
CVD_SAFE = {cvd_safe}           # series told apart by color under color-vision deficiency
GRAY_SAFE = {gray_safe}          # series told apart by lightness alone in grayscale print
SEQUENTIAL = {seq}
DIVERGING = {div}
DIAGRAM = {diagram}
ARROW = {arrow!r}

MARKERS = {markers}
LINESTYLES = {linestyles}


def tint(color, amount):
    """Keep `amount` (0..1) of '#RRGGBB', rest white; same as LaTeX xcolor `color!<amount*100>`
    and as drawing `color` with alpha=amount on white."""
    digits = color.lstrip("#")
    if len(digits) != 6 or not 0 <= amount <= 1:
        raise ValueError(f"tint expects '#RRGGBB' and 0 <= amount <= 1, got {{color!r}}, {{amount!r}}")
    rgb = [int(digits[i:i + 2], 16) for i in (0, 2, 4)]
    return "#" + "".join(f"{{round(amount * v + (1 - amount) * 255):02X}}" for v in rgb)


def ramp(role, n=None, lightest=1):
    """n ordered levels of one hue, light -> dark (small -> large model, weak -> strong).
    Uses steps lightest..last (step 1 is a fill color; pass lightest=2 for lines and markers).
    n=None: all those steps; n=1: the anchor; otherwise evenly spread incl. both ends."""
    if not 1 <= lightest <= len(RAMP[role]):
        raise ValueError(f"lightest must be 1..{{len(RAMP[role])}}, got {{lightest}}")
    steps = RAMP[role][lightest - 1:]
    if n is None:
        return list(steps)
    if not 1 <= n <= len(steps):
        raise ValueError(f"{{role}} ramp has {{len(steps)}} usable steps; asked for {{n}} levels")
    if n == 1:
        return [C[role]]
    return [steps[round(i * (len(steps) - 1) / (n - 1))] for i in range(n)]


def style(i, redundant=None):
    """kwargs for a series by ROLE NUMBER: 0 = ours, 1.. = base1.. (keep a method's number
    fixed across figures). Marker + linestyle are added when i >= CVD_SAFE, for every series
    with redundant=True (do this for grayscale print: only GRAY_SAFE series differ by
    lightness), and always past the last baseline, where colors repeat. Never returns neutral."""
    if i < 0:
        raise ValueError(f"series index must be >= 0, got {{i}}")
    use_shape = (i >= CVD_SAFE) if redundant is None else redundant
    kw = {{"color": SERIES[0] if i == 0 else SERIES[1 + (i - 1) % (len(SERIES) - 1)]}}
    if use_shape or i >= len(SERIES):
        kw.update(marker=MARKERS[i % len(MARKERS)], linestyle=LINESTYLES[i % len(LINESTYLES)])
    return kw


def cmap(kind="sequential"):
    """'sequential' (ours ramp), 'diverging' (base - neutral - ours), or a hue role's ramp."""
    from matplotlib.colors import LinearSegmentedColormap
    anchors = {{"sequential": SEQUENTIAL, "diverging": DIVERGING}}.get(kind) or RAMP[kind]
    return LinearSegmentedColormap.from_list(f"paper_{{kind}}", anchors)


def apply(redundant=False):
    """Set the matplotlib color cycle and register paper_sequential / paper_diverging /
    paper_<role> colormaps."""
    import matplotlib as mpl
    from cycler import cycler
    cyc = cycler(color=CYCLE)
    if redundant:
        cyc = cyc + cycler(marker=MARKERS[:len(CYCLE)])
    mpl.rcParams["axes.prop_cycle"] = cyc
    for kind in ["sequential", "diverging", *RAMP]:
        mpl.colormaps.register(cmap(kind), name=f"paper_{{kind}}", force=True)
    mpl.rcParams["image.cmap"] = "paper_sequential"
'''


def export_python(theme: Theme, stats: dict[str, int]) -> str:
    return _PY_TEMPLATE.format(
        name=theme.name, regen=REGEN.format(name=theme.name),
        colors=json.dumps(theme.colors, indent=4),
        codes=json.dumps(theme.codes, indent=4),
        ramps=json.dumps(theme.ramps, indent=4),
        ramp_codes=json.dumps(theme.ramp_codes).replace("null", "None"),
        anchor_step=json.dumps(theme.anchor_step),
        cycle=json.dumps(theme.cycle),
        series=json.dumps([theme.anchors[r] for r in theme.series]),
        cvd_safe=stats["cvd_safe"], gray_safe=stats["gray_safe"],
        seq=json.dumps(theme.sequential), div=json.dumps(theme.diverging),
        diagram=json.dumps({k: {"stroke": v["stroke"], "fill": v["fill"]}
                            for k, v in theme.diagram.items()}, indent=4),
        arrow=theme.arrow, markers=json.dumps(MARKERS), linestyles=repr(LINESTYLES),
    )


# ---------------------------------------------------------------------- LaTeX

def _rgb255(hex_color: str) -> str:
    return ",".join(str(round(c * 255)) for c in cl.parse_hex(hex_color))


def _definecolor(name: str, hex_color: str, comment: str = "") -> str:
    return f"\\definecolor{{{name}}}{{HTML}}{{{hex_color[1:]}}}" + (f" % {comment}" if comment else "")


def export_sty(theme: Theme, stats: dict[str, int]) -> str:
    defs = []
    for role in theme.hues:
        defs.append(_definecolor(tex_name(role), theme.anchors[role], f"code {theme.codes[role]}"))
        for k, (hex_c, code) in enumerate(zip(theme.ramps[role], theme.ramp_codes[role]), 1):
            defs.append(_definecolor(tex_step_name(role, k), hex_c,
                                     f"code {code}" if code else "derived"))
    for role in TEXT_ROLES:
        defs.append(_definecolor(tex_name(role), theme.text[role], theme.text_refs[role]))
    defs.append(_definecolor("cArrow", theme.arrow))
    tikz_styles = []
    for role, spec in theme.diagram.items():
        name = diagram_tex_name(role)
        defs += [_definecolor(name, spec["stroke"]), _definecolor(name + "Fill", spec["fill"])]
        tikz_styles.append(f"      pc {role}/.style={{draw={name}, fill={name}Fill, line width=0.8pt, "
                           f"rounded corners=2pt, text=black}},")
    cycle_list = ",".join(f"{{{tex_name(r)},mark={m}}}" for r, m in zip(theme.hues, PGF_MARKS))
    maps = [("paperseq", theme.sequential), ("paperdiv", theme.diverging)]
    maps += [(f"paper{r}", theme.ramps[r]) for r in theme.hues]
    colormaps = [f"    \\pgfplotsset{{colormap={{{n}}}{{{' '.join(f'rgb255=({_rgb255(c)})' for c in cs)}}}}}%"
                 for n, cs in maps]

    return "\n".join([
        f"% paper-colors.sty -- theme {theme.name}. GENERATED by the paper-colors skill; do not edit.",
        f"% Regenerate: {REGEN.format(name=theme.name)}",
        f"% Series told apart by color alone: {stats['cvd_safe']} (color-vision deficiency), "
        f"{stats['gray_safe']} (grayscale print). Beyond that, add marks / dashes.",
        "% Ramps: c<Role>S1 (lightest) .. S5 (darkest); ordered levels go light -> dark.",
        "\\NeedsTeXFormat{LaTeX2e}",
        f"\\ProvidesPackage{{paper-colors}}[2026/10/21 theme {theme.name}]",
        "\\newif\\ifpc@hyperref",
        "\\DeclareOption{hyperref}{\\pc@hyperreftrue}",
        "\\ProcessOptions\\relax",
        "\\RequirePackage{xcolor}",
        "\\RequirePackage{colortbl}",
        "",
        *defs,
        "",
        "% Tables: \\best{} bold, \\second{} underline, \\oursrow shades our row,",
        "% \\hlcell marks one cell. Text: \\gain{+1.2} / \\drop{-0.4}; captions: \\swatch{cOurs}.",
        "% Defined at \\begin{document} with \\providecommand: a preamble macro of the same name wins.",
        "\\AtBeginDocument{%",
        "  \\providecommand{\\best}[1]{\\textbf{#1}}%",
        "  \\providecommand{\\second}[1]{\\underline{#1}}%",
        f"  \\providecommand{{\\oursrow}}{{\\rowcolor{{{tex_step_name('ours', 1)}}}}}%",
        "  \\providecommand{\\hlcell}{\\cellcolor{cHighlight}}%",
        "  \\providecommand{\\gain}[1]{\\textcolor{cGain}{#1}}%",
        "  \\providecommand{\\drop}[1]{\\textcolor{cDrop}{#1}}%",
        "  \\providecommand{\\swatch}[1]{\\textcolor{#1}{\\rule{0.75em}{0.75em}}}%",
        "}",
        "",
        "\\AtBeginDocument{%",
        "  \\@ifpackageloaded{tikz}{%",
        "    \\tikzset{",
        *tikz_styles,
        "      pc arrow/.style={draw=cArrow, line width=0.8pt, -stealth},",
        "      pc ours arrow/.style={draw=cOurs, line width=1.2pt, -stealth},",
        "    }}{}%",
        "  \\@ifpackageloaded{pgfplots}{%",
        f"    \\pgfplotscreateplotcyclelist{{paper}}{{{cycle_list}}}%",
        *colormaps,
        "  }{}%",
        "  \\ifpc@hyperref\\@ifpackageloaded{hyperref}{%",
        "    \\hypersetup{colorlinks=true, linkcolor=cLink, citecolor=cLink, urlcolor=cLink}}{}\\fi",
        "}",
        "\\endinput",
        "",
    ])


# ----------------------------------------------------------------------- JSON

def export_tokens(theme: Theme, stats: dict[str, int]) -> str:
    """Hex tokens for draw.io / Figma / PowerPoint / Keynote."""
    diagram = {role: {"fill": spec["fill"], "stroke": spec["stroke"],
                      "drawio_style": f"fillColor={spec['fill']};strokeColor={spec['stroke']};"
                                      "fontColor=#000000;rounded=1;"}
               for role, spec in theme.diagram.items()}
    hues = {role: {"code": theme.codes[role], "anchor": theme.anchors[role],
                   "anchor_step": theme.anchor_step[role],
                   "ramp": [{"step": k, "hex": h, "code": c}
                            for k, (h, c) in enumerate(zip(theme.ramps[role], theme.ramp_codes[role]), 1)]}
            for role in theme.hues}
    return json.dumps({
        "theme": theme.name, "regenerate": REGEN.format(name=theme.name),
        "cvd_safe_series": stats["cvd_safe"], "grayscale_safe_series": stats["gray_safe"],
        "hues": hues,
        "text": {r: {"hex": theme.text[r], "from": theme.text_refs[r]} for r in TEXT_ROLES},
        "diagram": diagram, "arrow": theme.arrow,
        "sequential": theme.sequential, "diverging": theme.diverging,
    }, indent=2) + "\n"


# ------------------------------------------------------------------------ SVG

def export_svg(theme: Theme, stats: dict[str, int]) -> str:
    """Swatch sheet: each hue's ramp (book code under steps taken from the book), the ramp in
    grayscale, the anchor under protan / deutan / tritan; text roles; diagram boxes; colormaps."""
    sw, gap, left, top, row_h = 44, 4, 170, 76, 48
    steps = len(theme.ramps["ours"])
    gray_x = left + steps * (sw + gap) + 18
    cvd_x = gray_x + steps * (sw + gap) + 18
    parts = [f'<text x="16" y="28" font-size="18" font-weight="bold">paper-colors / {escape(theme.name)}</text>',
             f'<text x="16" y="48" font-size="11" fill="#555">{escape(theme.description)} '
             f'Safe series: {stats["cvd_safe"]} (CVD), {stats["gray_safe"]} (grayscale).</text>',
             f'<text x="{left}" y="{top - 8}" font-size="10" fill="#555">ramp, light → dark (★ anchor)</text>',
             f'<text x="{gray_x}" y="{top - 8}" font-size="10" fill="#555">grayscale</text>',
             f'<text x="{cvd_x}" y="{top - 8}" font-size="10" fill="#555">anchor: protan / deutan / tritan</text>']

    def rect(x, y, fill, w=sw, h=row_h - 22):
        return f'<rect x="{x}" y="{y}" width="{w}" height="{h}" fill="{fill}" stroke="#00000022"/>'

    for i, role in enumerate(theme.hues):
        y = top + i * row_h
        parts.append(f'<text x="16" y="{y + 15}" font-size="12">{role}</text>'
                     f'<text x="16" y="{y + 29}" font-size="9" fill="#555">{escape(theme.codes[role])}</text>')
        for k, (hex_c, code) in enumerate(zip(theme.ramps[role], theme.ramp_codes[role])):
            x = left + k * (sw + gap)
            star = " ★" if k + 1 == theme.anchor_step[role] else ""
            label = escape(code) if code else "derived"
            parts.append(rect(x, y, hex_c) + rect(gray_x + k * (sw + gap), y, cl.grayscale(hex_c))
                         + f'<text x="{x}" y="{y + row_h - 12}" font-size="7" font-family="monospace">'
                           f'{hex_c}{star}</text>'
                         + f'<text x="{x}" y="{y + row_h - 4}" font-size="6" fill="#555">{label}</text>')
        for j, kind in enumerate(cl.CVD_MATRICES):
            parts.append(rect(cvd_x + j * (sw + gap), y, cl.simulate_cvd(theme.anchors[role], kind)))

    y0 = top + len(theme.hues) * row_h + 16
    for j, role in enumerate(TEXT_ROLES):
        x = 16 + j * 150
        parts.append(rect(x, y0, theme.text[role], 30, 18)
                     + f'<text x="{x + 36}" y="{y0 + 13}" font-size="10">{role} = {theme.text_refs[role]}</text>')
    y1 = y0 + 40
    for i, (role, spec) in enumerate(theme.diagram.items()):
        x = 16 + i * 120
        parts.append(f'<rect x="{x}" y="{y1}" width="108" height="28" rx="4" fill="{spec["fill"]}" '
                     f'stroke="{spec["stroke"]}" stroke-width="1.6"/>'
                     f'<text x="{x + 54}" y="{y1 + 18}" font-size="11" text-anchor="middle">{role}</text>')
    y2 = y1 + 50
    for k, (label, anchors) in enumerate((("sequential", theme.sequential), ("diverging", theme.diverging))):
        x = 16 + k * 310
        stops = "".join(f'<stop offset="{n / (len(anchors) - 1):.2f}" stop-color="{c}"/>'
                        for n, c in enumerate(anchors))
        parts.append(f'<defs><linearGradient id="g{k}">{stops}</linearGradient></defs>'
                     f'<text x="{x}" y="{y2 - 4}" font-size="10" fill="#555">{label}</text>'
                     f'<rect x="{x}" y="{y2}" width="290" height="20" fill="url(#g{k})"/>')
    width = cvd_x + 3 * (sw + gap) + 20
    height = y2 + 40
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
            f'font-family="Helvetica, Arial, sans-serif"><rect width="100%" height="100%" fill="#FFFFFF"/>'
            + "".join(parts) + "</svg>\n")


